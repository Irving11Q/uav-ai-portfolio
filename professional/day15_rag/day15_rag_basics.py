# ════════════════════════════════════════════════════════════════
# 第 3 部分：切块（chunking）—— 长文档切成小块
# ════════════════════════════════════════════════════════════════
# 【解释】为什么切块？
#         ① 大模型一次能处理的文字有限（上下文窗口）；
#         ② 检索要"精准命中"，整篇文档一起比对，相似度会被稀释。
#         ③ 块太小丢上下文，块太大不精准 —— 这是切块的艺术。
#         今天手册每段就是一块（天然的段落切分），
#         Day16 会学"按标题/按字数"的进阶切法。

def chunk_manual(manual):
    # 【解释】切块函数：输入手册列表，输出"干净的块"列表。
    #         今天的切法最简单：每段就是一块，只做"去空白"清洗。

    chunks = []
    # 【解释】chunks = 装"干净块"的空列表。

    for para in manual:
        # 【解释】遍历手册里的每一段。

        text = para.strip()
        # 【解释】strip() 去掉段落首尾的多余空格/换行，保证块干净。

        if text:
            # 【解释】如果去掉空白后还有内容（防止空段落混进来）。

            chunks.append(text)
            # 【解释】把这块收进 chunks 列表。

    return chunks
    # 【解释】返回切好的块列表。

# ════════════════════════════════════════════════════════════════
# 第 4 部分：向量化（embedding）—— 文字变成数字
# ════════════════════════════════════════════════════════════════
# 【解释】核心思想：计算机不认识汉字，只认识数字。
#         我们要给每个块算一个"向量"（一串数字），
#         让"意思相近的块，向量也相近"。
#         真实项目用 embedding 模型（如 BGE/text2vec/OpenAI embedding），
#         今天为了离线可跑 + 原理透明，用最朴素的【字频向量】：
#         —— 先收集所有块里出现过的"字"，组成一本"词典"（vocab）；
#         —— 每个块统计：词典里每个字在块里出现了几次 → 一个向量。
#         例：词典 = ["电","池","温","度"]，某块 = "电池温度"
#             向量 = [1, 1, 1, 1]（每个字出现 1 次）。
#         这样"电池温度太高"和"电池温度超过60度"就会共享很多 1，
#         向量接近 → 相似度高。原理就这么简单！

def build_vocab(chunks):
    # 【解释】构建词典：把所有块里出现过的"字"收集起来、去重、排序。

    vocab = set()
    # 【解释】set（集合）= 自动去重的容器。先建一个空的。

    for chunk in chunks:
        # 【解释】遍历每个块。

        for ch in chunk:
            # 【解释】遍历块里的每个字符（汉字、字母、数字、标点都算）。

            if ch.strip():
                # 【解释】只收"非空白"字符（空格/换行不进词典，没意义）。

                vocab.add(ch)
                # 【解释】把字符收进集合（重复的自动被去掉）。

    return sorted(vocab)
    # 【解释】sorted 转成排好序的列表 —— 排序很重要！
    #         保证每次运行词典顺序一致，向量才能一一对应。

def make_vector(text, vocab):
    # 【解释】把一段文字变成向量（和词典对齐的一串数字）。

    counts = {}
    # 【解释】先建一个空字典：字 → 出现次数。

    for ch in text:
        # 【解释】遍历文字里的每个字符。

        if ch in vocab:
            # 【解释】只在词典里的字才计数（词典外的字忽略，保持维度固定）。

            counts[ch] = counts.get(ch, 0) + 1
            # 【解释】counts.get(ch, 0) = 取这个字原来的次数，没有就按 0；
            #         +1 表示又出现一次。整句意思：计数累加。

    return [counts.get(ch, 0) for ch in vocab]
    # 【解释】按词典顺序生成向量：词典里每个字，对应它在文本里的次数。
    #         没出现的字就是 0。例：词典["电","池","风"]，
    #         文本"电池"→ 向量 [1, 1, 0]。

# ════════════════════════════════════════════════════════════════
# 第 5 部分：检索（retrieval）—— 算相似度，找最相关的块
# ════════════════════════════════════════════════════════════════
# 【解释】检索的灵魂是【相似度计算】。这里用最经典的"余弦相似度"：
#         把两个向量看成空间里的两条"射线"，算它们夹角的余弦值。
#         cos(θ) = 1  → 方向完全一致（最相似）
#         cos(θ) = 0  → 垂直，毫不相关
#         公式：cos(θ) = A·B / (|A| × |B|)
#               分子 = 对应位置相乘再求和（点积）
#               分母 = 两个向量的长度（模）相乘

def cosine_sim(a, b):
    # 【解释】余弦相似度函数：输入两个向量，输出 0~1 的相似度。

    dot = sum(x * y for x, y in zip(a, b))
    # 【解释】分子：点积。zip(a, b) 把两个向量"按位置配对"，
    #         每一对相乘再求和。向量越像，点积越大。

    norm_a = math.sqrt(sum(x * x for x in a))
    # 【解释】向量 a 的长度（模）：每个数平方求和，再开平方。

    norm_b = math.sqrt(sum(x * x for x in b))
    # 【解释】向量 b 的长度（模），同上。

    if norm_a == 0 or norm_b == 0:
        # 【解释】如果某个向量全是 0（比如问题和词典毫无交集），
        #         分母为 0 会除零报错，所以兜底返回 0（不相似）。

        return 0.0
        # 【解释】返回 0.0：完全不相似。

    return dot / (norm_a * norm_b)
    # 【解释】核心公式：点积 ÷ (长度a × 长度b) = 余弦值（0~1）。

def search(question, chunks, vectors, vocab, top_k=3):
    # 【解释】检索函数：问题 → 相似度排序 → 返回最相关的 top_k 块。
    #         参数：question 问题、chunks 所有块、vectors 所有块向量、
    #         vocab 词典、top_k 取前几块（默认 3）。

    qv = make_vector(question, vocab)
    # 【解释】把"问题"也变成向量（同一本词典、同一个规则，才能比较）。

    scored = []
    # 【解释】scored = 装 (相似度, 块序号) 的列表。

    for i, vec in enumerate(vectors):
        # 【解释】enumerate = 边遍历边拿到序号 i 和向量 vec。

        sim = cosine_sim(qv, vec)
        # 【解释】算问题和这一块的相似度。

        scored.append((sim, i))
        # 【解释】记录：这一块的相似度 + 它在 chunks 里的位置。

    scored.sort(reverse=True)
    # 【解释】按相似度从高到低排序（reverse=True = 降序）。
    #         元组排序先比第一个元素（相似度），相同才比序号。

    return scored[:top_k]
    # 【解释】只取前 top_k 个（最相关的几块），返回列表。

# ════════════════════════════════════════════════════════════════
# 第 6 部分：生成（generation）—— 复用 api_config 调大模型
# ════════════════════════════════════════════════════════════════
# 【解释】检索只是"找资料"，最后必须让大模型"看着资料说话"。
#         做法：把检索到的块拼成"资料"，和问题一起塞进 Prompt，
#         并明确要求"只根据资料回答，资料没有的就说不知道"。
#         这样模型就不再瞎编 —— 这就是 RAG 的"增强生成"。

SYSTEM_PROMPT = (
    "你是无人机能耗助手。请只根据用户提供的【资料】回答，"
    "不要编造资料里没有的信息；资料里找不到答案就说'资料中没有提到'。"
)
# 【解释】System 消息：给模型立规矩（角色 + 约束）。
#         这是 Day12 学的 Prompt 工程在 RAG 里的实际应用！

def ask_model(messages):
    # 【解释】发一次请求给大模型，返回回答文字（和 Day10 一样的套路）。

    payload = {
        "model": MODEL_NAME,
        # 【解释】用 api_config 里的模型名（默认 glm-4-flash 免费档）。

        "messages": messages,
        # 【解释】消息列表：通常第一条是 system（规矩），第二条是 user（问题+资料）。

        "temperature": 0.3,
        # 【解释】温度低一点：问答要"稳定、贴资料"，不需要发散。
        #         （还记得 Day12 吗？温度低 = 更确定）

        "max_tokens": 300,
        # 【解释】限制回答长度，防止刷屏。

    }
    # 【解释】请求体：OpenAI 兼容格式，和 Day10 完全一样。

    resp = requests.post(
        BASE_URL + "/chat/completions",
        # 【解释】接口地址：api_config 里的地址 + 固定的 /chat/completions。

        headers={
            "Authorization": "Bearer " + API_KEY,
            # 【解释】身份凭证：Bearer + 你的 key。

            "Content-Type": "application/json",
            # 【解释】告诉服务器：我发的是 JSON 格式。
        },
        json=payload,
        # 【解释】把请求体以 JSON 形式发送。

        timeout=60,
        # 【解释】最多等 60 秒，防止卡死。
    )
    # 【解释】发送 POST 请求。

    if resp.status_code != 200:
        # 【解释】状态码不是 200 = 出错（常见：key 失效 / 限流）。

        return f"❌ 请求失败({resp.status_code})：{resp.json()}"
        # 【解释】返回错误信息，方便排查（比裸 KeyError 友好多了）。

    data = resp.json()
    # 【解释】解析响应的 JSON 成字典。

    return data["choices"][0]["message"]["content"]
    # 【解释】挖出回答文字（Day10 的经典取法）。

def rag_answer(question, chunks, hits):
    # 【解释】RAG 回答：把检索到的块拼成资料 → 发给模型。

    context = "\n\n".join(chunks[i] for _, i in hits)
    # 【解释】把命中的块按序号取出来，用空行连接成一段"资料"。

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        # 【解释】第一条：立规矩（只根据资料回答）。

        {
            "role": "user",
            "content": f"【资料】\n{context}\n\n【问题】{question}\n\n请根据资料回答：",
        },
        # 【解释】第二条：资料 + 问题。模型回答时会"看着"这段资料。
    ]
    # 【解释】两条消息 = RAG 生成环节的标准构造。

    return ask_model(messages)
    # 【解释】调用通用请求函数，拿到回答。

def direct_answer(question):
    # 【解释】对照组：不喂任何资料，直接问模型（模拟"没做 RAG"）。

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        # 【解释】同样立规矩（保持唯一变量 = 有没有资料）。

        {"role": "user", "content": question},
        # 【解释】只发问题，不带资料。

    ]
    # 【解释】注意：模型只能靠"训练时的记忆"回答，容易泛泛而谈或编造。

    return ask_model(messages)
    # 【解释】调用通用请求函数，拿到回答。

