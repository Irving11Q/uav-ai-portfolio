    vectors = [make_vector(c, vocab) for c in chunks]
    # 【解释】每个块都变成向量。列表推导式：对每个块 c 算一个向量。

    print(f"② 向量化完成：词典共 {len(vocab)} 个字，每个块 = {len(vocab)} 维向量")
