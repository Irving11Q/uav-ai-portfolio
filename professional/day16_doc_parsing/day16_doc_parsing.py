JSON_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "chunks_parsed.json")
# 【解释】输出文件路径：day16_doc_parsing/chunks_parsed.json。

def save_chunks_json(chunks, strategy, source):
    # 【解释】把切块结果存成 JSON 文件。

    records = []
    # 【解释】装"记录字典"的列表。

    for i, c in enumerate(chunks):
        # 【解释】enumerate = 边遍历边拿到序号 i（从 0 开始）。

        records.append({
            "id": i,
            # 【解释】块的序号（数据库里叫主键，Day17 入库时要用）。

            "text": c,
            # 【解释】块的内容。

            "source": source,
            # 【解释】来自哪个文件（追踪资料出处，RAG 回答可溯源）。

            "chunk_strategy": strategy,
            # 【解释】用哪种策略切的（实验记录，方便回看）。
        })
        # 【解释】每条记录 = 一个字典（JSON 的对象）。

    with open(JSON_FILE, "w", encoding="utf-8") as f:
        # 【解释】以写模式打开 JSON 输出文件。

        json.dump(records, f, ensure_ascii=False, indent=2)
        # 【解释】json.dump = 把列表写成 JSON 文件。
        #         ensure_ascii=False = 中文按原样存（默认会转成 \uXXXX）。
        #         indent=2 = 缩进两格，方便人眼看。

    print(f"💾 切块结果已保存：{JSON_FILE}（{len(records)} 条记录）")
    # 【解释】提示保存成功和记录条数。

