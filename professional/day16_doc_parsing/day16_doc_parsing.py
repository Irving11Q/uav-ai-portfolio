def read_manual(path):
    # 【解释】读取手册文件，返回"干净的纯文本"。

    with open(path, "r", encoding="utf-8", errors="replace") as f:
        # 【解释】以"读模式"打开。
        #         errors="replace" = 遇到无法解码的字节用 � 替换，
        #         而不是直接崩掉（真实文件常有脏字节，这是工程防御）。

        text = f.read()
        # 【解释】把整个文件内容读成一个大字符串。

    text = text.replace("\r\n", "\n")
    # 【解释】\r\n 是 Windows 的换行，\n 是 Unix 的。
    #         统一成 \n，避免后面按 \n 切分时混入 \r 脏字符。

    return text.strip()
    # 【解释】strip() 去掉开头结尾的多余空白，返回干净文本。

# ════════════════════════════════════════════════════════════════
# 第 4 部分：三种切块策略 —— 今天的核心
# ════════════════════════════════════════════════════════════════
# 【解释】切块 = 把一篇长文本切成 N 个小块。
#         为什么必须切？回顾 Day15：模型上下文有限 + 检索要精准。
#         但"怎么切"大有讲究 —— 下面三种策略各有优劣，面试常问。

def chunk_by_paragraph(text):
    # 【解释】策略 A：按段落切。段落的天然分隔符是"两个换行"（\n\n）。

    raw_paras = text.split("\n\n")
    # 【解释】把全文按 \n\n 切成若干段（Python 的 split 按分隔符拆）。

    chunks = []
    # 【解释】装"干净块"的空列表。

    for para in raw_paras:
        # 【解释】遍历每一段原始文字。

        line = para.strip()
        # 【解释】去掉这段首尾的空格/换行。

        if line:
            # 【解释】过滤掉空段（\n\n 之间可能夹着空白）。

            chunks.append(line)
            # 【解释】干净段落收进列表。

    return chunks
    # 【解释】返回段落块列表。优点：语义完整。缺点：长度不均，
    #         且标题行（如 "## 1. 电池规格"）会独自成块，和正文分离。

def chunk_by_window(text, size=60, overlap=15):
    # 【解释】策略 B：固定窗口切。每 size 个字符一块，
    #         下一块往前挪 (size - overlap) 个字符 —— 块与块之间重叠。

    chunks = []
    # 【解释】装块的空列表。

    step = size - overlap
    # 【解释】步长 = 每切一块，起点往前挪多少字符。
    #         重叠的意义：若一句话恰好被"拦腰切断"在窗口边缘，
    #         下一块还带着它前半句的尾巴，语义不至于断得太狠。

    i = 0
    # 【解释】当前窗口的起始位置（字符下标）。

    while i < len(text):
        # 【解释】只要还没扫完整个文本，就继续切。

        chunk = text[i : i + size]
        # 【解释】从 i 开始取 size 个字符，作为一块（切片操作）。

        if chunk.strip():
            # 【解释】过滤全空白的块（开头/结尾的空白区）。

            chunks.append(chunk.strip())
            # 【解释】收进列表。

        i += step
        # 【解释】起点往后挪一步，进入下一块。

    return chunks
    # 【解释】返回窗口块列表。优点：长度均匀、块数可控。
    #         缺点：无视段落边界，可能把语义切断（靠重叠缓解）。

def chunk_by_heading(text):
    # 【解释】策略 C：按标题切（markdown 的 ## 章节）。
    #         每个 "## 标题" 到下一个 "## 标题" 之间 = 一整块。

    lines = text.split("\n")
    # 【解释】先把全文按行拆开，逐行扫描找标题。

    chunks = []
    # 【解释】装块的空列表。

    current = []
    # 【解释】正在收集的当前块（一个列表，攒够了一整章再合并成字符串）。

    for line in lines:
        # 【解释】遍历每一行。

        if re.match(r"^#{1,3}\s", line):
            # 【解释】正则：以 1~3 个 # 加空格开头 = 这是标题行。
            #         ^ 行首，#{1,3} 一到三个 #，\s 一个空格。

            if current:
                # 【解释】如果手里已经攒了一个章节的内容。

                chunks.append("\n".join(current).strip())
                # 【解释】把这一章的行用换行拼起来，去掉首尾空白，收进列表。

            current = [line]
            # 【解释】开启新章节：标题行成为新块的第一行。

        else:
            # 【解释】不是标题行，是普通内容行。

            current.append(line)
            # 【解释】追加到当前章节里。

    if current:
        # 【解释】循环结束后，最后一章还在 current 里没被收走。

        chunks.append("\n".join(current).strip())
        # 【解释】收尾：把最后一章也收进列表。

    return chunks
    # 【解释】返回标题块列表。优点：按章节保留结构，每块自带标题，
    #         检索时一看就知道是哪一章的内容 —— 最推荐。

# ════════════════════════════════════════════════════════════════
# 第 5 部分：切块统计 —— 用数字对比三种策略
# ════════════════════════════════════════════════════════════════

def show_chunk_stats(name, chunks):
    # 【解释】打印某种切块策略的统计信息（块数、平均长度、最长/最短）。

    lengths = [len(c) for c in chunks]
    # 【解释】列表推导式：每个块的长度组成一个新列表。

    avg = sum(lengths) / len(lengths) if lengths else 0
    # 【解释】平均长度 = 总长度 ÷ 块数（空列表时兜底为 0）。

    print(f"  {name}: 共 {len(chunks)} 块 ｜ 平均 {avg:.0f} 字 ｜ "
          f"最短 {min(lengths) if lengths else 0} 字 ｜ 最长 {max(lengths) if lengths else 0} 字")
    # 【解释】一行打印全部统计：块数、平均、最短、最长。
    #         对比这三个数字，就能看出每种切法的"脾气"。

# ════════════════════════════════════════════════════════════════
# 第 6 部分：检索验证 —— 用 Day15 的检索看哪种切法"更准"
# ════════════════════════════════════════════════════════════════
# 【解释】切块好不好，光看数字不够，要看"检索效果"：
#         同一个问题，三种切法各自检索，命中块是不是真的相关？
#         这里直接复用 Day15 的 build_vocab / make_vector / search。

def verify_retrieval(question, chunks):
    # 【解释】对一组块做检索验证：建词典 → 算向量 → 检索 → 返回命中块。

    vocab = build_vocab(chunks)
    # 【解释】复用 Day15：收集所有块里的字，组成词典。

    vectors = [make_vector(c, vocab) for c in chunks]
    # 【解释】复用 Day15：每个块变成字频向量。

    hits = search(question, chunks, vectors, vocab, top_k=1)
    # 【解释】复用 Day15：问题和所有块算余弦相似度，取 Top-1。

    if not hits:
        # 【解释】理论上不会为空，防御一下。

        return "（无命中）"
        # 【解释】兜底返回。

    sim, idx = hits[0]
    # 【解释】解包：相似度 和 命中的块序号。

    return f"相似度 {sim:.3f}｜{chunks[idx][:45]}..."
    # 【解释】返回"相似度 + 命中块开头 45 个字"的描述。
    #         你观察哪个策略命中块里包含"55℃/鼓包"等关键词。

